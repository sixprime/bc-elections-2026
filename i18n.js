const supported = new Set(['en', 'fr']);
const languageFromUrl = () => new URLSearchParams(globalThis.location?.search || '').get('lang');
let language = supported.has(languageFromUrl()) ? languageFromUrl() : 'en';

export const locale = () => language === 'fr' ? 'fr-CA' : 'en-CA';
export const currentLanguage = () => language;
export const translatedMessages = french;

export function translate(message, values = {}) {
  const template = language === 'fr' && Object.hasOwn(french, message) ? french[message] : message;
  return template.replace(/\{([a-zA-Z][a-zA-Z0-9]*)\}/g, (token, name) => Object.hasOwn(values, name) ? String(values[name]) : token);
}

export function formatNumber(value, options = {}) {
  return new Intl.NumberFormat(locale(), options).format(value);
}

export function translateCount(count, singular, plural) {
  return translate(new Intl.PluralRules(locale()).select(count) === 'one' ? singular : plural, { count: formatNumber(count) });
}

export function formatPercent(value, decimals = 1) {
  return new Intl.NumberFormat(locale(), { style: 'percent', minimumFractionDigits: 0, maximumFractionDigits: decimals }).format(Number(value) / 100);
}

export function formatDate(value, options = {}) {
  const date = value instanceof Date ? value : new Date(/^\d{4}-\d{2}-\d{2}$/.test(value) ? `${value}T12:00:00Z` : value);
  return new Intl.DateTimeFormat(locale(), { timeZone: 'UTC', ...options }).format(date);
}

export function compareLabels(first, second) {
  return new Intl.Collator(locale(), { sensitivity: 'base', numeric: true }).compare(first, second);
}

export function translateElements(root = document) {
  for (const element of root.querySelectorAll('[data-i18n]')) element.textContent = translate(element.dataset.i18n);
  for (const attribute of ['aria-label', 'title', 'placeholder', 'content']) {
    for (const element of root.querySelectorAll(`[data-i18n-${attribute}]`)) element.setAttribute(attribute, translate(element.getAttribute(`data-i18n-${attribute}`)));
  }
  if (root === document) document.documentElement.lang = locale();
}

export function syncLanguageControls() {
  for (const input of document.querySelectorAll('input[data-language]')) input.checked = input.value === language;
}

export function setLanguage(next, updateUrl = true) {
  if (!supported.has(next)) return false;
  const changed = next !== language;
  language = next;
  if (typeof document !== 'undefined') document.documentElement.lang = locale();
  if (updateUrl && typeof history !== 'undefined') {
    const url = new URL(location.href);
    url.searchParams.set('lang', next);
    history.replaceState(history.state, '', url);
  }
  if (changed && typeof window !== 'undefined') window.dispatchEvent(new Event('languagechange'));
  return changed;
}

if (typeof window !== 'undefined') {
  const restoreLanguage = () => setLanguage(supported.has(languageFromUrl()) ? languageFromUrl() : 'en', false);
  window.addEventListener('popstate', restoreLanguage);
  window.addEventListener('routechange', restoreLanguage);
}
